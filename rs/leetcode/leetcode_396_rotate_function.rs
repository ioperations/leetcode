// You are given an integer array nums of length n.
//
// Assume arrk to be an array obtained by rotating nums by k positions
// clock-wise. We define the rotation function F on nums as follow:
//
// F(k) = 0 * arrk[0] + 1 * arrk[1] + ... + (n - 1) * arrk[n - 1].
// Return the maximum value of F(0), F(1), ..., F(n-1).
//
// The test cases are generated so that the answer fits in a 32-bit integer.
#[allow(unused)]
struct Solution;

impl Solution {
    #[allow(unused)]
    pub fn max_rotate_function(nums: Vec<i32>) -> i32 {
        let mut first: i64 = 0;

        let len = nums.len();
        for (i, item) in nums.iter().enumerate().take(len) {
            first += i as i64 * nums[i] as i64;
        }

        let sum: i64 = nums.iter().sum::<i32>() as i64;

        let mut ret = first;
        let mut curr = first;
        for i in 1..len {
            curr = curr + sum - (len as i64) * nums[len - i] as i64;

            ret = ret.max(curr);
        }

        ret as i32
    }
}

